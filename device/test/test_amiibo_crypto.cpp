// ---- AES-128 (encrypt only, CTR needs no decryption) ----

static void aes128ExpandKey(const uint8_t* key, uint8_t roundKeys[176]) {
  memcpy(roundKeys, key, 16);
  uint8_t rcon = 0x01;
  for (size_t i = 16; i < 176; i += 4) {
    uint8_t t[4];
    memcpy(t, roundKeys + i - 4, 4);
    if (i % 16 == 0) {
      uint8_t first = t[0];
      t[0] = AES_SBOX[t[1]] ^ rcon;
      t[1] = AES_SBOX[t[2]];
      t[2] = AES_SBOX[t[3]];
      t[3] = AES_SBOX[first];
      rcon = (uint8_t)((rcon << 1) ^ ((rcon & 0x80) ? 0x1B : 0));
    }
    for (int j = 0; j < 4; j++) roundKeys[i + j] = roundKeys[i - 16 + j] ^ t[j];
  }
}

static uint8_t gmul(uint8_t a, uint8_t b) {
  uint8_t p = 0;
  for (int i = 0; i < 8; i++) {
    if (b & 1) p ^= a;
    uint8_t hi = a & 0x80;
    a = (uint8_t)(a << 1);
    if (hi) a ^= 0x1B;
    b >>= 1;
  }
  return p;
}

static void aes128EncryptBlock(const uint8_t roundKeys[176], const uint8_t in[16],
                               uint8_t out[16]) {
  uint8_t s[16];
  memcpy(s, in, 16);
  for (int i = 0; i < 16; i++) s[i] ^= roundKeys[i];
  for (int round = 1; round <= 10; round++) {
    for (int i = 0; i < 16; i++) s[i] = AES_SBOX[s[i]];
    // ShiftRows on the column-major state: row r (i%4) rotates left by r.
    uint8_t t[16];
    for (int c = 0; c < 4; c++)
      for (int r = 0; r < 4; r++) t[c * 4 + r] = s[((c + r) % 4) * 4 + r];
    memcpy(s, t, 16);
    if (round != 10) {
      for (int c = 0; c < 4; c++) {
        uint8_t a0 = s[c*4], a1 = s[c*4+1], a2 = s[c*4+2], a3 = s[c*4+3];
        s[c*4+0] = gmul(a0, 2) ^ gmul(a1, 3) ^ a2 ^ a3;
        s[c*4+1] = a0 ^ gmul(a1, 2) ^ gmul(a2, 3) ^ a3;
        s[c*4+2] = a0 ^ a1 ^ gmul(a2, 2) ^ gmul(a3, 3);
        s[c*4+3] = gmul(a0, 3) ^ a1 ^ a2 ^ gmul(a3, 2);
      }
    }
    for (int i = 0; i < 16; i++) s[i] ^= roundKeys[round * 16 + i];
  }
  memcpy(out, s, 16);
}

extern "C" void otAes128CtrXor(const uint8_t* key, const uint8_t* iv,
                               uint8_t* data, size_t len) {
  uint8_t rk[176], ctr[16], ks[16];
  aes128ExpandKey(key, rk);
  memcpy(ctr, iv, 16);
  size_t off = 0;
  while (off < len) {
    aes128EncryptBlock(rk, ctr, ks);
    size_t n = (len - off < 16) ? len - off : 16;
    for (size_t i = 0; i < n; i++) data[off + i] ^= ks[i];
    off += n;
    for (int i = 15; i >= 0; i--) {  // 128-bit big-endian increment
      if (++ctr[i] != 0) break;
    }
  }
}

// ---- SHA-256 + HMAC ----

struct Sha256Ctx {
  uint32_t h[8];
  uint64_t total;
  uint8_t buf[64];
  size_t bufLen;
};

static uint32_t rotr32(uint32_t x, int n) { return (x >> n) | (x << (32 - n)); }

static void sha256Compress(uint32_t h[8], const uint8_t block[64]) {
  uint32_t w[64];
  for (int i = 0; i < 16; i++)
    w[i] = ((uint32_t)block[i*4] << 24) | ((uint32_t)block[i*4+1] << 16) |
           ((uint32_t)block[i*4+2] << 8) | (uint32_t)block[i*4+3];
  for (int i = 16; i < 64; i++) {
    uint32_t s0 = rotr32(w[i-15], 7) ^ rotr32(w[i-15], 18) ^ (w[i-15] >> 3);
    uint32_t s1 = rotr32(w[i-2], 17) ^ rotr32(w[i-2], 19) ^ (w[i-2] >> 10);
    w[i] = w[i-16] + s0 + w[i-7] + s1;
  }
  uint32_t a = h[0], b = h[1], c = h[2], d = h[3];
  uint32_t e = h[4], f = h[5], g = h[6], hh = h[7];
  for (int i = 0; i < 64; i++) {
    uint32_t S1 = rotr32(e, 6) ^ rotr32(e, 11) ^ rotr32(e, 25);
    uint32_t ch = (e & f) ^ (~e & g);
    uint32_t t1 = hh + S1 + ch + SHA256_K[i] + w[i];
    uint32_t S0 = rotr32(a, 2) ^ rotr32(a, 13) ^ rotr32(a, 22);
    uint32_t maj = (a & b) ^ (a & c) ^ (b & c);
    uint32_t t2 = S0 + maj;
    hh = g; g = f; f = e; e = d + t1;
    d = c; c = b; b = a; a = t1 + t2;
  }
  h[0] += a; h[1] += b; h[2] += c; h[3] += d;
  h[4] += e; h[5] += f; h[6] += g; h[7] += hh;
}

static void sha256Init(Sha256Ctx* ctx) {
  memcpy(ctx->h, SHA256_H, sizeof(ctx->h));
  ctx->total = 0;
  ctx->bufLen = 0;
}

static void sha256Update(Sha256Ctx* ctx, const uint8_t* data, size_t len) {
  ctx->total += len;
  while (len > 0) {
    size_t n = 64 - ctx->bufLen;
    if (n > len) n = len;
    memcpy(ctx->buf + ctx->bufLen, data, n);
    ctx->bufLen += n;
    data += n;
    len -= n;
    if (ctx->bufLen == 64) {
      sha256Compress(ctx->h, ctx->buf);
      ctx->bufLen = 0;
    }
  }
}

static void sha256Final(Sha256Ctx* ctx, uint8_t out[32]) {
  uint64_t bits = ctx->total * 8;
  uint8_t pad = 0x80;
  sha256Update(ctx, &pad, 1);
  uint8_t zero = 0;
  while (ctx->bufLen != 56) sha256Update(ctx, &zero, 1);
  uint8_t lenBe[8];
  for (int i = 0; i < 8; i++) lenBe[i] = (uint8_t)(bits >> (56 - 8 * i));
  sha256Update(ctx, lenBe, 8);
  for (int i = 0; i < 8; i++) {
    out[i*4+0] = (uint8_t)(ctx->h[i] >> 24);
    out[i*4+1] = (uint8_t)(ctx->h[i] >> 16);
    out[i*4+2] = (uint8_t)(ctx->h[i] >> 8);
    out[i*4+3] = (uint8_t)(ctx->h[i]);
  }
}

static void sha256(const uint8_t* data, size_t len, uint8_t out[32]) {
  Sha256Ctx ctx;
  sha256Init(&ctx);
  sha256Update(&ctx, data, len);
  sha256Final(&ctx, out);
}

extern "C" void otHmacSha256(const uint8_t* key, size_t keyLen,
                             const uint8_t* data, size_t len, uint8_t* out32) {
  uint8_t k[64] = {0};
  if (keyLen > 64) {
    sha256(key, keyLen, k);
  } else {
    memcpy(k, key, keyLen);
  }
  uint8_t ipad[64], opad[64];
  for (int i = 0; i < 64; i++) {
    ipad[i] = k[i] ^ 0x36;
    opad[i] = k[i] ^ 0x5C;
  }
  uint8_t inner[32];
  Sha256Ctx ctx;
  sha256Init(&ctx);
  sha256Update(&ctx, ipad, 64);
  sha256Update(&ctx, data, len);
  sha256Final(&ctx, inner);
  sha256Init(&ctx);
  sha256Update(&ctx, opad, 64);
  sha256Update(&ctx, inner, 32);
  sha256Final(&ctx, out32);
}

