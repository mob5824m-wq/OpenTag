static void testCryptoBackends() {
  // FIPS-197 appendix C.1
  uint8_t rk[176];
  aes128ExpandKey(KEY_FIPS197, rk);
  uint8_t ct[16];
  aes128EncryptBlock(rk, PT_FIPS197, ct);
  CHECK(memcmp(ct, CT_FIPS197, 16) == 0);

  // CTR keystream sanity: iv=0, len=16 -> ct = pt ^ AES_E(0)
  uint8_t zeroIv[16] = {0};
  uint8_t buf[16];
  memcpy(buf, PT_FIPS197, 16);
  uint8_t e0[16];
  aes128ExpandKey(KEY_FIPS197, rk);
  memset(e0, 0, 16);
  aes128EncryptBlock(rk, e0, e0);
  otAes128CtrXor(KEY_FIPS197, zeroIv, buf, 16);
  for (int i = 0; i < 16; i++) CHECK_EQ(buf[i], (uint8_t)(PT_FIPS197[i] ^ e0[i]));

  // FIPS-180-4: SHA-256("abc")
  uint8_t d[32];
  sha256((const uint8_t*)"abc", 3, d);
  CHECK(memcmp(d, SHA_ABC, 32) == 0);

  // RFC 4231 test cases 1 and 2
  uint8_t k1[20];
  memset(k1, 0x0b, sizeof(k1));
  otHmacSha256(k1, sizeof(k1), (const uint8_t*)"Hi There", 8, d);
  CHECK(memcmp(d, HMAC_RFC1, 32) == 0);
  otHmacSha256((const uint8_t*)"Jefe", 4,
               (const uint8_t*)"what do ya want for nothing?", 28, d);
  CHECK(memcmp(d, HMAC_RFC2, 32) == 0);

  // Counter increment across block boundary: encrypt 32 bytes, check that
  // the second block used counter 1.
  uint8_t iv[16] = {0};
  uint8_t a[32] = {0}, b[32] = {0};
  otAes128CtrXor(KEY_FIPS197, iv, a, 32);
  uint8_t iv1[16] = {0};
  iv1[15] = 1;
  otAes128CtrXor(KEY_FIPS197, iv1, b + 16, 16);
  CHECK(memcmp(a + 16, b + 16, 16) == 0);
}

static void testKeyFileHandling() {
  AmiiboKeys keys;
  CHECK(identifyKeyFile(REF_KEYS, 80) == KEY_DATA);
  CHECK(identifyKeyFile(REF_KEYS + 80, 80) == KEY_TAG);
  CHECK(identifyKeyFile(REF_KEYS, 79) == KEY_UNKNOWN);
  CHECK(identifyKeyFile(REF_KEYS, 160) == KEY_UNKNOWN);
  CHECK(identifyKeyFile(NULL, 80) == KEY_UNKNOWN);

  // Rubbish with no valid type string.
  uint8_t junk[80];
  memset(junk, 0xAB, sizeof(junk));
  CHECK(identifyKeyFile(junk, 80) == KEY_UNKNOWN);
  // Type string present but not NUL-terminated within 14 bytes.
  uint8_t unterminated[80];
  memcpy(unterminated, REF_KEYS, 80);
  memset(unterminated + 16, 'x', 14);
  CHECK(identifyKeyFile(unterminated, 80) == KEY_UNKNOWN);
  // magicBytesSize > 16 is rejected (matches amiitool's load_keys).
  uint8_t bigMagic[80];
  memcpy(bigMagic, REF_KEYS, 80);
  bigMagic[31] = 17;
  CHECK(identifyKeyFile(bigMagic, 80) == KEY_UNKNOWN);

  // loadKeyPair accepts either order.
  CHECK(loadKeyPair(REF_KEYS, 80, REF_KEYS + 80, 80, &keys));
  CHECK(memcmp(&keys, REF_KEYS, 160) == 0);
  CHECK(loadKeyPair(REF_KEYS + 80, 80, REF_KEYS, 80, &keys));
  CHECK(memcmp(&keys, REF_KEYS, 160) == 0);
  // Same file twice / junk is rejected.
  CHECK(!loadKeyPair(REF_KEYS, 80, REF_KEYS, 80, &keys));
  CHECK(!loadKeyPair(REF_KEYS, 80, junk, 80, &keys));
  CHECK(keysLoaded(&keys));
}

static void testLayoutConversion() {
  uint8_t intl[kPlainSize], back[kTagSize];
  tagToInternal(REF_TAG, intl);
  memset(back, 0xCC, sizeof(back));
  internalToTag(intl, back);
  CHECK(memcmp(back, REF_TAG, 520) == 0);  // crypto region round-trips

  // Spot-check the fixed moves against the amiitool table.
  CHECK(memcmp(intl + 0x1D4, REF_TAG, 8) == 0);   // uid prefix from tag[0]
  CHECK(memcmp(intl + 0x008, REF_TAG + 0x080, 0x20) == 0);
  CHECK(memcmp(intl + 0x04C, REF_TAG + 0x0A0, 0x168) == 0);
}

static void testUnpackAgainstAmiitool() {
  AmiiboKeys keys;
  loadKeyPair(REF_KEYS, 80, REF_KEYS + 80, 80, &keys);

  uint8_t plain[kPlainSize];
  CHECK(unpack(&keys, REF_TAG, plain));
  // HMAC areas are regenerated, everything else must match the amiitool
  // internal image bit for bit.
  CHECK(memcmp(plain, REF_PLAIN, 0x008) == 0);
  CHECK(memcmp(plain + 0x028, REF_PLAIN + 0x028, 0x18C) == 0);
  CHECK(memcmp(plain + 0x1D4, REF_PLAIN + 0x1D4, 0x34) == 0);

  // A single flipped bit anywhere in the encrypted region must fail.
  uint8_t tampered[kTagSize];
  memcpy(tampered, REF_TAG, kTagSize);
  tampered[0x50] ^= 0x01;
  CHECK(!unpack(&keys, tampered, plain));
  // ...and in the stored HMAC area.
  memcpy(tampered, REF_TAG, kTagSize);
  tampered[0x90] ^= 0x80;
  CHECK(!unpack(&keys, tampered, plain));
  // Wrong keys must fail too.
  AmiiboKeys bad;
  memcpy(&bad, &keys, sizeof(bad));
  bad.data.hmacKey[0] ^= 1;
  CHECK(!unpack(&bad, REF_TAG, plain));
}

static void testPackAgainstAmiitool() {
  AmiiboKeys keys;
  loadKeyPair(REF_KEYS, 80, REF_KEYS + 80, 80, &keys);

  uint8_t tag[kTagSize];
  memset(tag, 0, sizeof(tag));
  pack(&keys, REF_PLAIN, tag);
  CHECK(memcmp(tag, REF_TAG, 520) == 0);  // matches amiitool output exactly

  // Trailer pages (130..134) are deliberately untouched by pack().
  CHECK(tag[520] == 0 && tag[539] == 0);
}

